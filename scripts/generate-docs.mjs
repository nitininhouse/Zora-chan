import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const docsPath = join(root, "docs", "PROJECT_STRUCTURE.md");

function listDirs(path, depth = 0, maxDepth = 2) {
  if (depth > maxDepth) return [];
  return readdirSync(path, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => !entry.name.startsWith("."))
    .flatMap((entry) => {
      const fullPath = join(path, entry.name);
      return [
        { path: relative(root, fullPath).replaceAll("\\", "/"), depth },
        ...listDirs(fullPath, depth + 1, maxDepth),
      ];
    });
}

function listFiles(path, extensions) {
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = join(path, entry.name);
    if (entry.isDirectory()) return listFiles(fullPath, extensions);
    if (!extensions.some((ext) => entry.name.endsWith(ext))) return [];
    return relative(root, fullPath).replaceAll("\\", "/");
  });
}

function section(title, lines) {
  return [`## ${title}`, "", ...lines, ""].join("\n");
}

const appDirs = listDirs(join(root, "src", "app"));
const componentDirs = listDirs(join(root, "src", "components"));
const apiRoutes = listFiles(join(root, "src", "app", "api"), [".ts", ".tsx"]);
const packageJson = JSON.parse(
  readdirSync(root).includes("package.json")
    ? readFileSync(join(root, "package.json"), "utf8")
    : "{}",
);

const content = [
  "# Project Structure",
  "",
  "This file is generated by `npm run docs:generate`. Update source folders or scripts, then regenerate this file before opening a PR.",
  "",
  section(
    "Application Routes",
    appDirs.length
      ? appDirs.map((entry) => `${"  ".repeat(entry.depth)}- \`${entry.path}\``)
      : ["- No app routes found."],
  ),
  section(
    "Component Areas",
    componentDirs.length
      ? componentDirs.map(
          (entry) => `${"  ".repeat(entry.depth)}- \`${entry.path}\``,
        )
      : ["- No component directories found."],
  ),
  section(
    "API Routes",
    apiRoutes.length
      ? apiRoutes.map((route) => `- \`${route}\``)
      : ["- No API routes found."],
  ),
  section(
    "Package Scripts",
    Object.entries(packageJson.scripts ?? {}).map(
      ([name, command]) => `- \`${name}\`: \`${command}\``,
    ),
  ),
].join("\n");

writeFileSync(docsPath, content);
